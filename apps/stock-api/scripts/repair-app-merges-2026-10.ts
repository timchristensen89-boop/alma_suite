/**
 * Repairs the 27 duplicate merges made in the app (Items → Duplicates) on
 * 17 Oct 2026 at 06:48–06:50 AEDT, and the Agave Syrup edit saved at 06:50.
 *
 * The app's merge SUMS the two records' holdings and FOLDS two lines on one
 * sheet by addition. Where one record was the leftover of an older count (the
 * other was counted on 1 Oct), that double counts. Where the two records count
 * in different units (a 12.5 kg flour bag into a per-kg record, 5 L juice
 * containers into a per-litre record) it adds unlike quantities.
 *
 * What this does, all driven by docs/stock-app-merge-repair-2026-10/repair-data.json
 * (generated by comparing the 06:37 production copy with the current one):
 *   1. History: puts back every stocktake line the merges deleted and every
 *      line they added together, exactly as recorded. Lines stay pointed at
 *      the surviving record (repoint-only, as for every scripted merge).
 *   2. Movements: points each stock movement back at the line it came from.
 *   3. Holdings: sets each surviving record's venue holding to the pre-merge
 *      holding of the side counted on that venue's latest sheet, converted to
 *      the survivor's unit, and drops the leftover side. Each change writes a
 *      STOCKTAKE_CORRECTION movement.
 *   4. Items: Agave Syrup back to the 4 L tub; Lime and Watermelon Juice
 *      bought as 5 L containers counted in litres; one placeholder price removed.
 *
 * Dry run by default. --apply writes (snapshot first, one transaction).
 * --rollback <runId> restores every snapshotted row and removes what the run
 * created. Every row is checked against what was reviewed; any difference
 * refuses the whole run. Production needs --i-mean-production.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { Prisma } from '@prisma/client';
import { prisma } from '@alma/db';

const BACKUP = '_stock_app_merge_repair_backup';
const here = path.dirname(fileURLToPath(import.meta.url));
const DEFAULT_DATA = path.resolve(here, '../../../docs/stock-app-merge-repair-2026-10/repair-data.json');

type Json = Record<string, unknown>;
type Data = {
  restoreLines: Json[];
  revertLines: Array<{ id: string; set: Json; expectNow: Json }>;
  relinkMovements: Array<{ id: string; sourceStocktakeLineId: string | null; expectNow: string | null }>;
  holdings: Array<{ itemId: string; item: string; venue: string; countUnit: string; expectNow: number; onHand: number; evidence: boolean; kept?: Json[]; dropped?: Json[]; latestSheet?: string }>;
  items: Array<{ id: string; item: string; why: string; expectNow: Json; set: Json }>;
};

const args = process.argv.slice(2);
const flag = (name: string) => args.includes(name);
const value = (name: string) => {
  const i = args.indexOf(name);
  return i >= 0 ? args[i + 1] : undefined;
};

const near = (a: unknown, b: unknown) => {
  if (a === null || a === undefined || b === null || b === undefined) return (a ?? null) === (b ?? null);
  if (typeof a === 'number' || typeof b === 'number') return Math.abs(Number(a) - Number(b)) < 1e-6;
  if (a instanceof Date) return a.toISOString() === new Date(String(b)).toISOString();
  return String(a) === String(b);
};

async function guardDatabase() {
  const [{ db }] = await prisma.$queryRawUnsafe<Array<{ db: string }>>('SELECT current_database() AS db');
  const production = /alma_suite_v18/.test(db);
  console.log(`database: ${db}${production ? ' — PRODUCTION' : ''}`);
  if (production && (flag('--apply') || flag('--rollback')) && !flag('--i-mean-production')) {
    throw new Error('This is production. Add --i-mean-production to write.');
  }
}

async function ensureBackupTable() {
  await prisma.$executeRawUnsafe(`CREATE TABLE IF NOT EXISTS "${BACKUP}" (
    id bigserial PRIMARY KEY, "runId" text NOT NULL, step text NOT NULL, "tableName" text NOT NULL,
    "rowId" text NOT NULL, payload jsonb NOT NULL, "createdAt" timestamptz NOT NULL DEFAULT now())`);
}

/** Every difference between what was reviewed and what is there now. */
async function check(data: Data): Promise<string[]> {
  const problems: string[] = [];
  const restoreIds = data.restoreLines.map((row) => String(row.id));
  const already = await prisma.stocktakeLine.findMany({ where: { id: { in: restoreIds } }, select: { id: true } });
  for (const row of already) problems.push(`line ${row.id} to restore already exists`);
  const itemIds = Array.from(new Set(data.restoreLines.map((row) => String(row.itemId))));
  const found = new Set((await prisma.stockItem.findMany({ where: { id: { in: itemIds } }, select: { id: true } })).map((r) => r.id));
  for (const id of itemIds) if (!found.has(id)) problems.push(`item ${id} for a restored line is missing`);

  const lines = new Map((await prisma.stocktakeLine.findMany({ where: { id: { in: data.revertLines.map((l) => l.id) } } })).map((l) => [l.id, l]));
  for (const fix of data.revertLines) {
    const line = lines.get(fix.id) as unknown as Json | undefined;
    if (!line) { problems.push(`line ${fix.id} is gone`); continue; }
    for (const [key, expected] of Object.entries(fix.expectNow)) {
      if (!near(line[key], expected)) problems.push(`line ${fix.id} ${key} is ${String(line[key])}, reviewed ${String(expected)}`);
    }
  }
  const moves = new Map((await prisma.inventoryMovement.findMany({ where: { id: { in: data.relinkMovements.map((m) => m.id) } } })).map((m) => [m.id, m]));
  for (const fix of data.relinkMovements) {
    const move = moves.get(fix.id);
    if (!move) problems.push(`movement ${fix.id} is gone`);
    else if (move.sourceStocktakeLineId !== fix.expectNow) problems.push(`movement ${fix.id} now points at ${move.sourceStocktakeLineId}`);
  }
  for (const h of data.holdings) {
    const row = await prisma.venueStockItem.findFirst({ where: { stockItemId: h.itemId, venue: h.venue } });
    if (!row) problems.push(`${h.item} @ ${h.venue}: no holding`);
    else if (!near(row.onHand, h.expectNow)) problems.push(`${h.item} @ ${h.venue}: holding is ${row.onHand}, reviewed ${h.expectNow}`);
  }
  for (const fix of data.items) {
    const item = (await prisma.stockItem.findUnique({ where: { id: fix.id } })) as unknown as Json | null;
    if (!item) { problems.push(`${fix.item} is missing`); continue; }
    for (const [key, expected] of Object.entries(fix.expectNow)) {
      if (!near(item[key], expected)) problems.push(`${fix.item} ${key} is ${String(item[key])}, reviewed ${String(expected)}`);
    }
  }
  return problems;
}

async function valuation() {
  const rows = await prisma.$queryRawUnsafe<Array<{ venue: string; cents: number }>>(`
    SELECT v.venue, round(sum(v."onHand" * s."avgCostCents"))::float AS cents
    FROM "VenueStockItem" v JOIN "StockItem" s ON s.id = v."stockItemId"
    WHERE s.status = 'ACTIVE' AND v.venue IN ('Alma Avalon','St Alma') AND v."onHand" IS NOT NULL AND s."avgCostCents" IS NOT NULL
    GROUP BY v.venue ORDER BY v.venue`);
  for (const row of rows) console.log(`  ${row.venue}: active stock value $${(row.cents / 100).toFixed(2)}`);
}

function describe(data: Data, costs: Map<string, number | null>) {
  console.log(`\n== History: ${data.restoreLines.length} deleted lines put back, ${data.revertLines.length} added-together lines restored, ${data.relinkMovements.length} movements relinked`);
  console.log(`\n== Holdings (${data.holdings.length})`);
  const byVenue = new Map<string, number>();
  for (const h of data.holdings) {
    const cost = costs.get(h.itemId) ?? 0;
    const delta = (h.onHand - h.expectNow) * cost;
    byVenue.set(h.venue, (byVenue.get(h.venue) ?? 0) + delta);
    const kept = (h.kept ?? []).map((k) => `${k.item} ${k.onHand}${Number(k.factor) !== 1 ? ` × ${Number(k.factor)}` : ''}`).join(' + ') || 'nothing';
    const dropped = (h.dropped ?? []).map((k) => `${k.item} ${k.onHand}`).join(', ');
    console.log(`  ${h.item} @ ${h.venue}: ${h.expectNow} → ${h.onHand} ${h.countUnit}  ($${(delta / 100).toFixed(2)})`);
    console.log(`      kept: ${kept}${dropped ? `; dropped as leftover: ${dropped}` : ''}${h.evidence ? '' : ' — neither counted on the latest sheet; kept the main record'}`);
  }
  for (const [venue, cents] of byVenue) console.log(`  → ${venue}: $${(cents / 100).toFixed(2)} at today's costs`);
  console.log(`\n== Items (${data.items.length})`);
  for (const fix of data.items) console.log(`  ${fix.item}: ${JSON.stringify(fix.expectNow)} → ${JSON.stringify(fix.set)}\n      ${fix.why}`);
}

const toDate = (v: unknown) => (typeof v === 'string' && /^\d{4}-\d{2}-\d{2}T/.test(v) ? new Date(v.endsWith('Z') ? v : `${v}Z`) : v);

async function apply(data: Data, runId: string) {
  await ensureBackupTable();
  const existing = await prisma.$queryRawUnsafe<Array<{ n: number }>>(`SELECT count(*)::int n FROM "${BACKUP}" WHERE "runId" = $1`, runId);
  if (existing[0]!.n > 0) throw new Error(`Run ${runId} already exists.`);
  const appliedAt = new Date();
  await prisma.$transaction(async (tx) => {
    const snap = async (step: string, table: string, rows: Json[]) => {
      for (const row of rows) {
        await tx.$executeRawUnsafe(`INSERT INTO "${BACKUP}" ("runId",step,"tableName","rowId",payload) VALUES ($1,$2,$3,$4,$5::jsonb)`, runId, step, table, String(row.id), JSON.stringify(row));
      }
    };
    await snap('run', 'run', [{ id: runId, appliedAt: appliedAt.toISOString() }]);
    await snap('before', 'StocktakeLine', (await tx.stocktakeLine.findMany({ where: { id: { in: data.revertLines.map((l) => l.id) } } })) as unknown as Json[]);
    await snap('before', 'InventoryMovement', (await tx.inventoryMovement.findMany({ where: { id: { in: data.relinkMovements.map((m) => m.id) } } })) as unknown as Json[]);
    const holdingIds = data.holdings.map((h) => h.itemId);
    const itemIds = Array.from(new Set([...holdingIds, ...data.items.map((i) => i.id)]));
    await snap('before', 'VenueStockItem', (await tx.venueStockItem.findMany({ where: { stockItemId: { in: holdingIds } } })) as unknown as Json[]);
    await snap('before', 'StockItem', (await tx.stockItem.findMany({ where: { id: { in: itemIds } } })) as unknown as Json[]);

    // 1. History.
    for (const row of data.restoreLines) {
      const data_ = Object.fromEntries(Object.entries(row).map(([k, v]) => [k, toDate(v)]));
      await tx.stocktakeLine.create({ data: data_ as Prisma.StocktakeLineUncheckedCreateInput });
      await snap('created', 'StocktakeLine', [{ id: row.id }]);
    }
    for (const fix of data.revertLines) {
      await tx.stocktakeLine.update({ where: { id: fix.id }, data: fix.set as Prisma.StocktakeLineUncheckedUpdateInput });
    }
    for (const fix of data.relinkMovements) {
      await tx.inventoryMovement.update({ where: { id: fix.id }, data: { sourceStocktakeLineId: fix.sourceStocktakeLineId } });
    }
    // 2. Items (units first, so the correction movements carry the right unit).
    for (const fix of data.items) {
      const set = Object.fromEntries(Object.entries(fix.set).map(([k, v]) => [k, toDate(v)]));
      await tx.stockItem.update({ where: { id: fix.id }, data: set as Prisma.StockItemUncheckedUpdateInput });
    }
    // 3. Holdings.
    for (const h of data.holdings) {
      const row = await tx.venueStockItem.findFirstOrThrow({ where: { stockItemId: h.itemId, venue: h.venue } });
      const before = row.onHand ?? 0;
      await tx.venueStockItem.update({ where: { id: row.id }, data: { onHand: h.onHand } });
      const movement = await tx.inventoryMovement.create({
        data: {
          itemId: h.itemId, movementType: 'STOCKTAKE_CORRECTION', quantityBefore: before, quantityAfter: h.onHand,
          quantityDelta: h.onHand - before, unit: h.countUnit, createdAt: appliedAt,
          notes: `${h.venue}: duplicate merge of 17 Oct repaired (run ${runId}) — holdings had been added together`
        }
      });
      await snap('created', 'InventoryMovement', [{ id: movement.id }]);
    }
    for (const id of itemIds) {
      const rows = await tx.venueStockItem.findMany({ where: { stockItemId: id, onHand: { not: null } }, select: { onHand: true } });
      await tx.stockItem.update({ where: { id }, data: { onHand: rows.reduce((sum, r) => sum + (r.onHand ?? 0), 0) } });
    }
  }, { maxWait: 15_000, timeout: 120_000 });
  console.log(`\nApplied run ${runId}. Rollback: --rollback ${runId}`);
}

async function rollback(runId: string) {
  await ensureBackupTable();
  const rows = await prisma.$queryRawUnsafe<Array<{ step: string; tableName: string; rowId: string; payload: Json }>>(
    `SELECT step, "tableName", "rowId", payload FROM "${BACKUP}" WHERE "runId" = $1 ORDER BY id`, runId);
  if (!rows.length) throw new Error(`No snapshot for run ${runId}`);
  if (rows.some((r) => r.step === 'rolled_back')) throw new Error(`Run ${runId} was already rolled back.`);
  const appliedAt = new Date(String(rows.find((r) => r.step === 'run')!.payload.appliedAt));
  const createdMoves = rows.filter((r) => r.step === 'created' && r.tableName === 'InventoryMovement').map((r) => r.rowId);
  const touchedItems = rows.filter((r) => r.tableName === 'StockItem').map((r) => r.rowId);
  const later = await prisma.inventoryMovement.count({ where: { itemId: { in: touchedItems }, createdAt: { gt: appliedAt }, id: { notIn: createdMoves } } });
  if (later > 0 && !flag('--force')) throw new Error(`${later} stock movement(s) on these items happened after the run. Rolling back would overwrite them; re-run with --force only after checking.`);
  await prisma.$transaction(async (tx) => {
    await tx.inventoryMovement.deleteMany({ where: { id: { in: createdMoves } } });
    const before = (table: string) => rows.filter((r) => r.step === 'before' && r.tableName === table).map((r) => r.payload);
    for (const p of before('InventoryMovement')) await tx.inventoryMovement.update({ where: { id: String(p.id) }, data: { sourceStocktakeLineId: (p.sourceStocktakeLineId as string | null) ?? null } });
    await tx.stocktakeLine.deleteMany({ where: { id: { in: rows.filter((r) => r.step === 'created' && r.tableName === 'StocktakeLine').map((r) => r.rowId) } } });
    for (const p of before('StocktakeLine')) {
      await tx.stocktakeLine.update({ where: { id: String(p.id) }, data: { countedQty: p.countedQty as number | null, stockValueCents: p.stockValueCents as number | null, notes: p.notes as string | null, updatedAt: toDate(p.updatedAt) as Date } });
    }
    for (const p of before('VenueStockItem')) await tx.venueStockItem.update({ where: { id: String(p.id) }, data: { onHand: p.onHand as number | null, active: p.active as boolean, updatedAt: toDate(p.updatedAt) as Date } });
    for (const p of before('StockItem')) {
      const { id, createdAt: _c, ...rest } = p;
      const data = Object.fromEntries(Object.entries(rest).map(([k, v]) => [k, toDate(v)]));
      await tx.stockItem.update({ where: { id: String(id) }, data: data as Prisma.StockItemUncheckedUpdateInput });
    }
    await tx.$executeRawUnsafe(`INSERT INTO "${BACKUP}" ("runId",step,"tableName","rowId",payload) VALUES ($1,'rolled_back','run',$1,'{}'::jsonb)`, runId);
  }, { maxWait: 15_000, timeout: 120_000 });
  console.log(`Rolled back run ${runId}.`);
}

async function main() {
  await guardDatabase();
  const rollbackId = value('--rollback');
  if (rollbackId) {
    await rollback(rollbackId);
    await valuation();
    return;
  }
  const data = JSON.parse(fs.readFileSync(value('--data') ?? DEFAULT_DATA, 'utf8')) as Data;
  const costs = new Map((await prisma.stockItem.findMany({ where: { id: { in: data.holdings.map((h) => h.itemId) } }, select: { id: true, avgCostCents: true } })).map((r) => [r.id, r.avgCostCents]));
  describe(data, costs);
  const problems = await check(data);
  if (problems.length) {
    console.log(`\nREFUSED — ${problems.length} difference(s) from what was reviewed:`);
    for (const p of problems.slice(0, 40)) console.log(`  ${p}`);
    process.exitCode = 1;
    return;
  }
  console.log('\nEvery row matches what was reviewed.');
  if (!flag('--apply')) {
    console.log('Dry run — nothing written. Re-run with --apply.');
    await valuation();
    return;
  }
  await apply(data, value('--run-id') ?? `app-merge-repair-${new Date().toISOString().slice(0, 19).replace(/[:T]/g, '')}`);
  await valuation();
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exitCode = 1;
}).finally(() => prisma.$disconnect());
